import { api } from './api.js';

export const listStudents = () => api.select('students', { order: ['student_code', 'asc'] });
export const getStudent = (id) => api.get('students', id);
export function saveStudent(row) {
  const data = { ...row };
  if (data.guardian_consent && !data.guardian_consent_at) data.guardian_consent_at = new Date().toISOString();
  delete data.student_code; // generated by the database
  return row.id ? api.update('students', row.id, data) : api.insert('students', data);
}
